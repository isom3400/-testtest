import streamlit as st
from transformers import pipeline

# 1. Load the text-generation pipeline (the new way to handle chats)
@st.cache_resource
def load_chatbot():
    # We use "text-generation" now instead of the removed "conversational" task
    return pipeline("text-generation", model="facebook/blenderbot-400M-distill")

chatbot = load_chatbot()

# 2. Initialize Chat History
if "messages" not in st.session_state:
    st.session_state.messages = []

# 3. App UI Layout
st.title("🤖 Your AI Companion")
st.write("Talk to this open-source AI chatbot!")

# Display past chat messages from history
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# 4. Accept User Input
if user_input := st.chat_input("Say something to the AI..."):
    # Display user message
    with st.chat_message("user"):
        st.markdown(user_input)
    
    # Add user message to history using standard OpenAI/HuggingFace layout
    st.session_state.messages.append({"role": "user", "content": user_input})

    # 5. Generate AI Response
    with st.chat_message("assistant"):
        with st.spinner("Thinking..."):
            # Simply pass the message list history directly to the pipeline
            outputs = chatbot(st.session_state.messages, max_new_tokens=50)
            
            # Extract the newest response string generated by the assistant
            ai_response = outputs[0]["generated_text"][-1]["content"]
            st.markdown(ai_response)
            
    # Add assistant response to chat history
    st.session_state.messages.append({"role": "assistant", "content": ai_response})

